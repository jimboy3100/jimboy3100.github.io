#!/usr/bin/env node
/*
 * Builds the Legend Express extension's texts from developers/i18n/src (the extension cannot load the
 * mod's language files: its popup and its agar.io loading/error screens run before Legend Mod).
 *
 *   node developers/i18n/extension.js           write the files
 *   node developers/i18n/extension.js --check   only compare; exit 1 when a file is stale
 *
 * Output (committed, no build step on the site):
 *   LMexpress/extension/texts.js                every lmx.ext.* text and boot.loading in the 12 languages,
 *                                               used by popup.html/popup.js and content.js
 *   LMexpress/extension/_locales/<code>/messages.json   the manifest's description (chrome.i18n follows
 *                                               the browser's language: the store page and chrome://extensions)
 * The popup and the agar.io screens follow Legend Mod's Choose Language (languagemod), like the mod.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const I = require('./lib');

const EXT = path.join(I.ROOT, 'LMexpress', 'extension');
/* Chrome's locale folder names for the 12 languages (Traditional Chinese is zh_TW) */
const CHROME = { en: 'en', el: 'el', es: 'es', bg: 'bg', fr: 'fr', ar: 'ar', zh: 'zh_TW', ru: 'ru', de: 'de', tr: 'tr', pl: 'pl', nl: 'nl' };
/* manifest field -> key (Chrome allows 132 characters in a description) */
const MANIFEST = { description: 'lmx.ext.storeDescription' };

const ascii = (s) => s.replace(/[^\x00-\x7f]/g, (ch) => '\\u' + ch.charCodeAt(0).toString(16).padStart(4, '0'));

function build() {
    const all = I.readAll();
    const rows = {};
    Object.keys(all).forEach((a) => Object.keys(all[a]).forEach((k) => {
        if (k.indexOf('lmx.ext.') === 0 || k === 'boot.loading') rows[k] = all[a][k];
    }));
    const files = {};
    const lines = Object.keys(rows).sort().map((k) => {
        const e = rows[k];
        return '    ' + JSON.stringify(k) + ': [' + I.CODES.map((c) => ascii(JSON.stringify(e[c] || e.en))).join(', ') + ']';
    });
    files['LMexpress/extension/texts.js'] =
        '/* GENERATED by developers/i18n/extension.js from developers/i18n/src/*.json: do not edit by hand.\n' +
        ' * Change the texts in developers/i18n/src and run: node developers/i18n/extension.js */\n' +
        '/* key -> texts in the Choose Language order: ' + I.CODES.join(' ') + ' (languagemod 1..12) */\n' +
        'var LMX_EXT_TEXTS = {\n' + lines.join(',\n') + '\n};\n' +
        'var LMX_EXT_CODES = ' + JSON.stringify(I.CODES).replace(/,/g, ', ') + ';\n' +
        '/* the language number (1..12): the one chosen in Legend Mod, else the browser\'s, else English */\n' +
        'function lmxExtLang(chosen) {\n' +
        '    var n = parseInt(chosen, 10);\n' +
        '    if (n >= 1 && n <= 12) return n;\n' +
        "    var i = LMX_EXT_CODES.indexOf(String((navigator && navigator.language) || '').slice(0, 2).toLowerCase());\n" +
        '    return i >= 0 ? i + 1 : 1;\n' +
        '}\n' +
        '/* the text of key in language n (1..12), English when that language has none */\n' +
        'function lmxExtText(key, n) {\n' +
        '    var row = LMX_EXT_TEXTS[key];\n' +
        '    if (!row) return key;\n' +
        '    return row[(n || 1) - 1] || row[0];\n' +
        '}\n';
    I.CODES.forEach((c) => {
        const msgs = {};
        Object.keys(MANIFEST).forEach((field) => {
            const e = rows[MANIFEST[field]];
            if (!e) throw new Error('missing ' + MANIFEST[field]);
            const text = e[c] || e.en;
            if (text.length > 132) throw new Error(MANIFEST[field] + ' (' + c + ') is longer than Chrome allows (132)');
            msgs[field] = { message: text };
        });
        files['LMexpress/extension/_locales/' + CHROME[c] + '/messages.json'] = JSON.stringify(msgs, null, 2) + '\n';
    });
    const us = userscriptRegion(all);
    if (us) files['LMexpress/LMexpress.user.js'] = us;
    return files;
}

/* LMexpress.user.js (the userscript loader) runs alone in Tampermonkey: its texts are written into it
 * between the i18n:texts markers (ASCII, the file is ASCII) */
const US_KEYS = (k) => k.indexOf('lmx.us.') === 0 || ['lmx.ext.website', 'lmx.ext.library', 'lmx.ext.tryAgain'].indexOf(k) >= 0;
function userscriptRegion(all) {
    const file = path.join(I.ROOT, 'LMexpress', 'LMexpress.user.js');
    if (!fs.existsSync(file)) return null;
    const src = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    const A = '/* i18n:texts-start */', B = '/* i18n:texts-end */';
    const a = src.indexOf(A), b = src.indexOf(B);
    if (a < 0 || b < a) return null;
    const rows = [];
    Object.keys(all).forEach((ar) => Object.keys(all[ar]).sort().forEach((k) => {
        if (!US_KEYS(k)) return;
        const e = all[ar][k];
        rows.push('    ' + JSON.stringify(k) + ': [' + I.CODES.map((c) => ascii(JSON.stringify(e[c] || e.en))).join(', ') + ']');
    }));
    const region = A + ' /* GENERATED by developers/i18n/extension.js: change the texts in developers/i18n/src */\n' +
        'var LMX_US_TEXTS = {\n' + rows.join(',\n') + '\n};\n';
    return src.slice(0, a) + region + src.slice(b);
}

const norm = (s) => s.replace(/\r\n/g, '\n');
function run(check) {
    const files = build();
    const stale = [];
    Object.keys(files).sort().forEach((rel) => {
        const file = path.join(I.ROOT, rel);
        const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
        if (old !== null && norm(old) === norm(files[rel])) return;
        stale.push(rel);
        if (!check) {
            fs.mkdirSync(path.dirname(file), { recursive: true });
            const crlf = old !== null ? /\r\n/.test(old) : false;
            fs.writeFileSync(file, crlf ? norm(files[rel]).replace(/\n/g, '\r\n') : files[rel]);
        }
    });
    return { files, stale };
}

module.exports = { build, run, EXT };

if (require.main === module) {
    const check = process.argv.indexOf('--check') >= 0;
    const { files, stale } = run(check);
    if (check) {
        if (stale.length) { console.log('stale (run node developers/i18n/extension.js): ' + stale.join(', ')); process.exit(1); }
        console.log('extension texts up to date (' + Object.keys(files).length + ' files)');
    } else {
        console.log(stale.length ? 'wrote ' + stale.join(', ') : 'nothing to do (' + Object.keys(files).length + ' files up to date)');
    }
}
