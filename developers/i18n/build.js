#!/usr/bin/env node
/*
 * Builds the language files from developers/i18n/src/*.json (no dependencies, deterministic).
 *
 *   node developers/i18n/build.js           write the files
 *   node developers/i18n/build.js --check   only compare; exit 1 and list the files that are stale
 *
 * Output (all committed: the site has no build step):
 *   languages/lm-<code>.js         the mod's texts (every area except site*), one per language
 *   languages/lm-site-<code>.js, lm-site-<page>-<code>.js   the web pages' texts (site.json, site-<page>.json: one file each)
 *   languages/lm-i18n.js           runtime for the mod (developers/i18n/runtime.js + old global names)
 *   lib/lm-i18n.js                 runtime for the web pages (same file in page mode)
 *   languages/LanguagePack<Name>.js  the old addresses: small loaders for the files above
 *   play.html                      the loading-screen texts between the i18n:boot markers
 */
'use strict';
const fs = require('fs');
const path = require('path');
const I = require('./lib');

const HEADER = '/* GENERATED by developers/i18n/build.js from developers/i18n/src/*.json: do not edit by hand.\n' +
    ' * Change the texts in developers/i18n/src and run: node developers/i18n/build.js */\n';

/* one "key": "text" per line, so a changed text is a one-line diff */
function dictLines(dict) {
    const keys = Object.keys(dict);
    return '{\n' + keys.map((k, i) => JSON.stringify(k) + ': ' + JSON.stringify(dict[k]) + (i < keys.length - 1 ? ',' : '')).join('\n') + '\n}';
}

/* JSON.stringify leaves U+2028/2029 raw, which older engines reject inside a script string */
const safe = (s) => s.split(String.fromCharCode(0x2028)).join('\\u2028').split(String.fromCharCode(0x2029)).join('\\u2029');

function build() {
    const all = I.readAll();
    const files = {};
    /* the mod gets every non-site area in one file per language; each site area is its own file, so a
     * page loads only the shared site texts and its own */
    const bundles = {};
    const aliases = {};
    Object.keys(all).forEach((area) => {
        const b = I.isSiteArea(area) ? area : 'mod';
        if (!bundles[b]) { bundles[b] = {}; I.CODES.forEach((c) => { bundles[b][c] = {}; }); }
        Object.keys(all[area]).forEach((key) => {
            const e = all[area][key];
            if (e.global) aliases[e.global] = key;
            I.CODES.forEach((c) => {
                const v = e[c];
                /* English keeps empty texts that are empty on purpose; other languages fall back to it */
                if (typeof v === 'string' && (v !== '' || c === 'en')) bundles[b][c][key] = v;
            });
        });
    });
    Object.keys(bundles).sort().forEach((b) => {
        I.CODES.forEach((c) => {
            const name = 'lm-' + (b === 'mod' ? '' : b + '-') + c + '.js';
            files['languages/' + name] = HEADER +
                '/* ' + I.PACK_NAMES[c] + ' (' + c + ', languagemod ' + (I.CODES.indexOf(c) + 1) + '): ' + Object.keys(bundles[b][c]).length + ' texts */\n' +
                '(window._lmI18nQueue = window._lmI18nQueue || []).push([' + JSON.stringify(c) + ', ' + JSON.stringify(b) + ', ' + safe(dictLines(bundles[b][c])) + ']);\n' +
                'if (window.LMi18n && window.LMi18n._drain) window.LMi18n._drain();\n';
        });
    });

    const runtime = fs.readFileSync(path.join(__dirname, 'runtime.js'), 'utf8').replace(/\r\n/g, '\n');
    if (/[^\x00-\x7f]/.test(runtime)) throw new Error('developers/i18n/runtime.js must be ASCII (write \\u escapes)');
    const aliasSrc = 'var ALIASES = ' + JSON.stringify(aliases, Object.keys(aliases).sort()).replace(/","/g, '",\n        "') + '; /* old global -> key */';
    const mark = (s, from, to) => { if (s.indexOf(from) < 0) throw new Error('runtime.js: marker missing: ' + from); return s.replace(from, to); };
    files['languages/lm-i18n.js'] = HEADER + mark(runtime, 'var ALIASES = {}; /* @ALIASES@ */', aliasSrc);
    files['lib/lm-i18n.js'] = HEADER + mark(runtime, 'var SITE = false; /* @SITE@ */', 'var SITE = true; /* the web pages */');

    I.CODES.forEach((c) => {
        files['languages/LanguagePack' + I.PACK_NAMES[c] + '.js'] = shim(c);
    });

    const boot = bootRegion(all);
    if (boot) files['play.html'] = boot;
    return files;
}

/* Old address languages/LanguagePack<Name>.js (other pages and scripts load it by URL): it switches
 * the old globals to that language, as loading the old pack did. */
function shim(c) {
    return HEADER +
        '/* Legend Mod language pack: ' + I.PACK_NAMES[c] + '. The texts are in developers/i18n/src (languages/lm-' + c + '.js);\n' +
        ' * this old address loads them and switches Languageletter*, Premadeletter*, Externalletter* and translator. */\n' +
        '(function () {\n' +
        "    var code = '" + c + "', base = 'https://www.legendmod.ml/languages/', W = window, cs = document.currentScript;\n" +
        "    var v = (function () { var m = cs && /[?&]v=([^&#]+)/.exec(cs.src || ''); return m ? '?v=' + m[1] : ''; })();\n" +
        "    var use = function () { if (W.LMi18n) W.LMi18n.setLang(code, { save: false }); };\n" +
        "    if (W.LMi18n && W.LMi18n.loaded(code, 'mod') && W.LMi18n.loaded('en', 'mod')) { use(); return; }\n" +
        "    var files = (W.LMi18n ? [] : ['lm-i18n.js']).concat(['lm-en.js', 'lm-' + code + '.js']);\n" +
        "    if (document.readyState === 'loading' && cs && !cs.async && !cs.defer) {\n" +
        "        for (var i = 0; i < files.length; i++) document.write('<script src=\"' + base + files[i] + v + '\" charset=\"utf-8\"><\\/script>');\n" +
        "        document.write('<script>window.LMi18n && window.LMi18n.setLang(\"' + code + '\", { save: false });<\\/script>');\n" +
        '        return;\n' +
        '    }\n' +
        '    var next = function (i) {\n' +
        '        if (i >= files.length) { use(); return; }\n' +
        "        var s = document.createElement('script');\n" +
        "        s.charset = 'utf-8';\n" +
        '        s.src = base + files[i] + v;\n' +
        '        s.onload = s.onerror = function () { next(i + 1); };\n' +
        '        (document.head || document.documentElement).appendChild(s);\n' +
        '    };\n' +
        '    next(0);\n' +
        '})();\n';
}

/* play.html's loading screen runs before any file: its "Loading..." texts are written into it */
function bootRegion(all) {
    const file = path.join(I.ROOT, 'play.html');
    if (!fs.existsSync(file)) return null;
    const html = fs.readFileSync(file, 'utf8');
    const a = html.indexOf('/* i18n:boot-start */');
    const b = html.indexOf('/* i18n:boot-end */');
    if (a < 0 || b < a) return null;
    let e = null;
    Object.keys(all).forEach((area) => { if (all[area]['boot.loading']) e = all[area]['boot.loading']; });
    if (!e) return null;
    const nl = html.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
    const list = I.CODES.map((c) => JSON.stringify(e[c] || e.en).replace(/[^\x00-\x7f]/g, (ch) => '\\u' + ch.charCodeAt(0).toString(16).padStart(4, '0')));
    const region = '/* i18n:boot-start */ /* GENERATED from developers/i18n/src (boot.loading) by build.js */' + nl +
        '            var LANG_TEXT = [' + list.join(', ') + '];' + nl + '            ';
    return html.slice(0, a) + region + html.slice(b);
}

const norm = (s) => s.replace(/\r\n/g, '\n');
function run(check) {
    const files = build();
    const stale = [];
    Object.keys(files).sort().forEach((rel) => {
        const file = path.join(I.ROOT, rel);
        const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
        if (old !== null && norm(old) === norm(files[rel])) return;
        stale.push(rel);
        if (!check) {
            /* keep the line endings the file has in this checkout */
            const crlf = old !== null ? /\r\n/.test(old) : false;
            fs.writeFileSync(file, crlf ? norm(files[rel]).replace(/\n/g, '\r\n') : norm(files[rel]));
        }
    });
    return { files, stale };
}

module.exports = { build, run };

if (require.main === module) {
    const check = process.argv.indexOf('--check') >= 0;
    const { files, stale } = run(check);
    if (check) {
        if (stale.length) { console.log('stale (run node developers/i18n/build.js): ' + stale.join(', ')); process.exit(1); }
        console.log('language files up to date (' + Object.keys(files).length + ' files)');
    } else {
        console.log(stale.length ? 'wrote ' + stale.join(', ') : 'nothing to do (' + Object.keys(files).length + ' files up to date)');
    }
}
